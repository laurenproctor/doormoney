/*
  Geometry in the flipped, scaled space. The mark spans x 152..410 and y 140..602 (258 by 462).
  The letters as drawn span x 645..2065 and y 306..426 (1420 by 120), which is small next to the mark,
  so the lockup enlarges them by WORD_SCALE and sets them GAP units to the right of the mark, centred on it.
*/
const MARK_BOX = { x: 152, y: 140, w: 258, h: 462 };
const WORD_BOX = { x: 645, y: 306, w: 1420, h: 120 };
const WORD_SCALE = 1.375;
const GAP = 180;
const wordX = MARK_BOX.x + MARK_BOX.w + GAP;
const wordY = MARK_BOX.y + MARK_BOX.h / 2 - (WORD_BOX.h * WORD_SCALE) / 2;
const WORD_TRANSFORM = `translate(${wordX - WORD_BOX.x * WORD_SCALE},${wordY - WORD_BOX.y * WORD_SCALE}) scale(${WORD_SCALE})`;
const FLIP = "translate(0,724) scale(0.1,-0.1)";
const BOX = {
  lockup: `${MARK_BOX.x} ${MARK_BOX.y} ${wordX + WORD_BOX.w * WORD_SCALE - MARK_BOX.x} ${MARK_BOX.h}`,
  mark: `${MARK_BOX.x} ${MARK_BOX.y} ${MARK_BOX.w} ${MARK_BOX.h}`,
} as const;

export function Logo({
  variant = "lockup",
  className = "",
  title = SITE.name,
}: {
  variant?: "lockup" | "mark";
  className?: string;
  /** Accessible name. Pass an empty string when the parent already labels the logo. */
  title?: string;
}) {
  return (
    <svg
      viewBox={BOX[variant]}
      className={className}
      fill="currentColor"
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
    >
      {title ? <title>{title}</title> : null}
      <g transform={FLIP}>
        {MARK.map((d, i) => (
          <path key={i} d={d} />
        ))}
      </g>
      {variant === "lockup" ? (
        <g transform={WORD_TRANSFORM}>
          <g transform={FLIP}>
            {WORDMARK.map((d, i) => (
              <path key={i} d={d} />
            ))}
          </g>
        </g>
      ) : null}
    </svg>
  );
}
